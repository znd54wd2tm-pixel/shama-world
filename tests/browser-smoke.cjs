/* Run against the explicit local development server only. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.SHAMA_TEST_URL || 'http://127.0.0.1:8765';
if(!/^http:\/\/(127\.0\.0\.1|localhost):/.test(base))throw Error('Browser tests require a local development server');
let browser;
(async()=>{
  browser=await chromium.launch({executablePath:process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,args:['--disable-gpu-sandbox','--use-angle=swiftshader']});
  const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  const page=await context.newPage();
  const errors=[],checks=[];
  page.on('pageerror',(e)=>errors.push(e.message));
  page.on('response',(r)=>{if(r.url().startsWith(base)&&r.status()>=500)errors.push(`${r.status()} ${r.url()}`);});
  await page.route('https://telegram.org/**',(route)=>route.fulfill({body:'',contentType:'application/javascript'}));
  await page.route('https://fonts.googleapis.com/**',(route)=>route.fulfill({body:'',contentType:'text/css'}));
  const check=(name,value)=>{assert.ok(value,name);checks.push(name);console.log('PASS',name);};
  await page.goto(base,{waitUntil:'networkidle'});
  await page.waitForSelector('#app:not(.is-hidden)');
  await page.locator('.nav-item[data-nav="cases"]').click();
  await page.locator('[data-case-id]').first().click();
  await page.waitForSelector('#case-modal:not(.is-hidden)');
  await page.waitForFunction(()=>document.querySelector('#case-scene').dataset.renderer==='three');
  check('Real Three.js WebGL canvas on mobile',await page.locator('#case-scene canvas').count()===1);
  check('Single price button',(await page.locator('#open-case-button').textContent())==='Открыть 1 за $100');
  check('Ten price button',(await page.locator('#open-ten-cases-button').textContent())==='Открыть 10 за $1 000');
  check('Fast mode off by default',await page.locator('#fast-open-toggle').getAttribute('aria-pressed')==='false');
  await page.screenshot({path:path.join(__dirname,'../.test-data/mobile-case.png')});
  await page.locator('#fast-open-toggle').click();
  await page.waitForFunction(()=>document.querySelector('#fast-open-toggle').getAttribute('aria-pressed')==='true');
  check('Lightning enables fast mode',(await page.locator('#toast').textContent())==='⚡ Быстрый прокрут включён');
  check('Heavy preview disposed in fast mode',await page.locator('#case-scene canvas').count()===0);
  const start=Date.now();
  await page.locator('#open-ten-cases-button').click();
  await page.waitForSelector('#opening-result:not(.is-hidden)');
  check('Fast ten shows all ten results',await page.locator('.result-mini').count()===10);
  check('Fast result has no five second animation',Date.now()-start<2500);
  await page.locator('#result-batch [data-result-focus="4"]').click();
  check('Each result can be inspected',await page.locator('.result-mini.is-focused').count()===1);
  await page.screenshot({path:path.join(__dirname,'../.test-data/mobile-ten.png')});
  const balanceBefore=await page.evaluate(async()=> (await (await fetch('/api/me')).json()).balance);
  const openingsBefore=await page.evaluate(async()=> (await (await fetch('/api/me')).json()).cases_opened);
  await page.reload({waitUntil:'networkidle'});
  await page.waitForSelector('#opening-result:not(.is-hidden)');
  check('Result restored after reload',await page.locator('.result-mini').count()===10);
  check('Reload does not charge twice',await page.evaluate(async()=> (await (await fetch('/api/me')).json()).balance)>=balanceBefore && await page.evaluate(async()=> (await (await fetch('/api/me')).json()).cases_opened)===openingsBefore);
  await page.locator('#saved-button').click();
  await page.locator('#opening-modal').waitFor({state:'hidden'});
  await page.locator('.nav-item[data-nav="cases"]').click();
  await page.locator('[data-case-id]').first().click();
  check('Fast preference survives reload',await page.locator('#fast-open-toggle').getAttribute('aria-pressed')==='true');
  await page.locator('#fast-open-toggle').click();
  await page.waitForFunction(()=>document.querySelector('#fast-open-toggle').getAttribute('aria-pressed')==='false');
  check('Lightning disables fast mode',(await page.locator('#toast').textContent())==='Быстрый прокрут выключен');
  const normalStart=Date.now();
  await page.locator('#open-case-button').click();
  await page.waitForSelector('#opening-3d canvas');
  await page.waitForSelector('#opening-result:not(.is-hidden)',{timeout:12000});
  check('Normal mode uses full opening duration',Date.now()-normalStart>=4700);
  await page.locator('#opening-sell-button').click();
  await page.waitForFunction(()=>document.querySelector('#result-description').textContent==='Предмет продан');
  check('Instant sale is confirmed by the server',await page.locator('#opening-sell-button').isHidden());
  await page.locator('#opening-close').click();
  await page.locator('.nav-item[data-nav="earn"]').click();
  await page.waitForSelector('.business-card');
  check('Owned business with real income controls',await page.locator('.business-rates').count()>0);
  await page.screenshot({path:path.join(__dirname,'../.test-data/mobile-businesses.png')});
  await page.locator('.nav-item[data-nav="market"]').click();
  await page.waitForSelector('.player-market');
  check('Player market integrated',await page.locator('#list-inventory-form').count()===1);
  check('No page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  check('No browser JavaScript errors',errors.length===0);
  fs.writeFileSync(path.join(__dirname,'../.test-data/browser-checks.json'),JSON.stringify({checks,errors},null,2));
  await browser.close();
})().catch(async(error)=>{console.error(error);await browser?.close();process.exitCode=1;});
